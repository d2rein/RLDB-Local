import fs from "node:fs/promises";
import path from "node:path";
import { SEED_DIR } from "./lib/project-paths.mjs";
import { sqlBoolean, sqlNumber, sqlString } from "./lib/sql.mjs";
import { FULL_HISTORICAL_RESEED_DELETE_STATEMENTS } from "./lib/seed-delete-order.mjs";

const bundlePath = path.join(SEED_DIR, "core_import_bundle.json");
const sqlOutputPath = path.join(SEED_DIR, "0002_core_seed.sql");

const bundle = JSON.parse(await fs.readFile(bundlePath, "utf8"));

const competitionIdByCode = new Map([
  ["NRL", 1],
  ["NRLW", 2],
  ["SOO", 3],
  ["WSOO", 4],
]);

const teamIdByName = new Map();
bundle.teams.forEach((team, index) => {
  teamIdByName.set(team.canonicalName, index + 1);
});

const venueIdByName = new Map();
bundle.venues.forEach((venue, index) => {
  venueIdByName.set(venue.canonicalName, index + 1);
});

const playerIdByName = new Map();
bundle.players.forEach((player, index) => {
  playerIdByName.set(player.displayName, index + 1);
});

function winnerTeamId(match) {
  if (match.homeScore === null || match.awayScore === null) {
    return null;
  }
  if (match.homeScore > match.awayScore) {
    return teamIdByName.get(match.homeTeam) ?? null;
  }
  if (match.awayScore > match.homeScore) {
    return teamIdByName.get(match.awayTeam) ?? null;
  }
  return null;
}

function margin(match) {
  if (match.homeScore === null || match.awayScore === null) {
    return null;
  }
  return Math.abs(match.homeScore - match.awayScore);
}

const statements = [];
statements.push("-- Generated by scripts/build-core-seed-sql.mjs");
statements.push("BEGIN TRANSACTION;");
statements.push(...FULL_HISTORICAL_RESEED_DELETE_STATEMENTS);
statements.push("");

bundle.venues.forEach((venue, index) => {
  statements.push(
    `INSERT INTO venues (venue_id, canonical_name, afltables_name, nrl_name, city, country) VALUES (${index + 1}, ${sqlString(
      venue.canonicalName
    )}, ${sqlString(venue.afltablesName)}, ${sqlString(venue.nrlName)}, NULL, NULL);`
  );
});

statements.push("");

bundle.teams.forEach((team, index) => {
  statements.push(
    `INSERT INTO teams (team_id, competition_id, canonical_name, short_name, first_season, last_season, is_active) VALUES (${index + 1}, ${
      competitionIdByCode.get(team.competitionCode) ?? 1
    }, ${sqlString(team.canonicalName)}, ${sqlString(team.canonicalName)}, ${sqlNumber(team.firstSeason)}, ${sqlNumber(
      team.lastSeason
    )}, 1);`
  );
});

statements.push("");

bundle.players.forEach((player, index) => {
  statements.push(
    `INSERT INTO players (player_id, display_name, sort_name, first_season, last_season, afltables_player_url, is_unresolved) VALUES (${index + 1}, ${sqlString(
      player.displayName
    )}, ${sqlString(player.displayName)}, ${sqlNumber(player.firstSeason)}, ${sqlNumber(player.lastSeason)}, ${sqlString(player.afltablesPlayerUrl ?? null)}, ${sqlBoolean(
      player.isUnresolved === 1
    )});`
  );
});

statements.push("");

bundle.playerAliases.forEach((alias, index) => {
  statements.push(
    `INSERT INTO player_aliases (player_alias_id, player_id, source, source_name, first_season, last_season, confidence) VALUES (${index + 1}, ${
      playerIdByName.get(alias.canonicalName) ?? "NULL"
    }, ${sqlString(alias.source)}, ${sqlString(alias.sourceName)}, ${sqlNumber(alias.firstSeason)}, ${sqlNumber(
      alias.lastSeason
    )}, ${sqlNumber(alias.confidence)});`
  );
});

statements.push("");

bundle.matches.forEach((match) => {
  statements.push(
    `INSERT INTO matches (match_id, competition_id, season, round_label, round_index, match_date_utc, match_date_local_text, is_finals, home_team_id, away_team_id, home_score, away_score, winner_team_id, margin, venue_id, notes) VALUES (${sqlNumber(
      match.matchId
    )}, ${competitionIdByCode.get(match.competitionCode) ?? 1}, ${sqlNumber(match.season)}, ${sqlString(
      match.roundLabel
    )}, ${sqlNumber(match.roundIndex)}, ${sqlString(match.matchDateUtc)}, ${sqlString(
      match.matchDateLocalText
    )}, ${sqlBoolean(match.isFinals === 1)}, ${teamIdByName.get(match.homeTeam) ?? "NULL"}, ${
      teamIdByName.get(match.awayTeam) ?? "NULL"
    }, ${sqlNumber(match.homeScore)}, ${sqlNumber(match.awayScore)}, ${sqlNumber(winnerTeamId(match))}, ${sqlNumber(
      margin(match)
    )}, ${sqlNumber(venueIdByName.get(match.venue) ?? null)}, ${sqlString(match.notes)});`
  );
});

statements.push("");

let matchSourceId = 1;
for (const match of bundle.matches) {
  for (const [source, payload] of Object.entries(match.sources)) {
    if (!payload.present) {
      continue;
    }

    statements.push(
      `INSERT INTO match_sources (match_source_id, match_id, source, source_match_key, source_round_label, source_round_index, source_date, source_home_team, source_away_team, source_home_score, source_away_score, source_venue, source_url) VALUES (${matchSourceId}, ${sqlNumber(
        match.matchId
      )}, ${sqlString(source)}, ${sqlString(payload.matchKey ?? null)}, ${sqlString(payload.round ?? null)}, ${sqlNumber(
        payload.roundIndex
      )}, ${sqlString(payload.date ?? null)}, ${sqlString(payload.homeTeam ?? null)}, ${sqlString(
        payload.awayTeam ?? null
      )}, ${sqlNumber(payload.homeScore)}, ${sqlNumber(payload.awayScore)}, ${sqlString(
        payload.venue ?? null
      )}, ${sqlString(payload.url ?? null)});`
    );
    matchSourceId += 1;
  }
}

statements.push("");
statements.push("COMMIT;");

await fs.writeFile(sqlOutputPath, `${statements.join("\n")}\n`, "utf8");

console.log("Core seed SQL:", sqlOutputPath);
console.log("Teams:", bundle.teams.length);
console.log("Venues:", bundle.venues.length);
console.log("Players:", bundle.players.length);
console.log("Player aliases:", bundle.playerAliases.length);
console.log("Matches:", bundle.matches.length);
