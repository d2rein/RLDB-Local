import fs from "node:fs/promises";
import path from "node:path";
import { STAT_DEFINITIONS, STAT_GROUPS } from "../src/server/config/stat-definitions.mjs";
import { parseCsv } from "./lib/csv.mjs";
import { DOCS_DIR, SEED_DIR } from "./lib/project-paths.mjs";
import { sqlBoolean, sqlNumber, sqlString } from "./lib/sql.mjs";

const OVERRIDES_CSV = path.join(DOCS_DIR, "player_reconciliation_overrides.csv");

const competitions = [
  { competitionId: 1, code: "NRL", name: "National Rugby League" },
  { competitionId: 2, code: "NRLW", name: "National Rugby League Women" },
  { competitionId: 3, code: "SOO", name: "State of Origin" },
  { competitionId: 4, code: "WSOO", name: "Women's State of Origin" },
];

await fs.mkdir(SEED_DIR, { recursive: true });

const overrideRows = parseCsv(await fs.readFile(OVERRIDES_CSV, "utf8"));
const approvedOverrides = overrideRows.filter((row) => String(row.status ?? "").toLowerCase() === "approved");

const groupIdByCode = new Map(STAT_GROUPS.map((group, index) => [group.code, index + 1]));
const resetTablesInOrder = [
  "player_match_summary",
  "team_match_summary",
  "player_stat_aggregates",
  "legacy_player_scoring",
  "match_player_stats",
  "match_team_stats",
  "match_sources",
  "player_team_spells",
  "import_issues",
  "player_aliases",
  "team_aliases",
  "matches",
  "players",
  "teams",
  "venues",
  "import_runs",
  "stat_definitions",
  "stat_groups",
  "competitions",
];

const statements = [];
statements.push("-- Generated by scripts/build-reference-seed.mjs");
statements.push("BEGIN TRANSACTION;");
for (const tableName of resetTablesInOrder) {
  statements.push(`DELETE FROM ${tableName};`);
}
statements.push("");

for (const competition of competitions) {
  statements.push(
    `INSERT INTO competitions (competition_id, code, name) VALUES (${competition.competitionId}, ${sqlString(
      competition.code
    )}, ${sqlString(competition.name)});`
  );
}

statements.push("");

STAT_GROUPS.forEach((group, index) => {
  statements.push(
    `INSERT INTO stat_groups (stat_group_id, code, label, sort_order) VALUES (${index + 1}, ${sqlString(
      group.code
    )}, ${sqlString(group.label)}, ${group.sortOrder});`
  );
});

statements.push("");

STAT_DEFINITIONS.forEach((stat, index) => {
  statements.push(
    [
      "INSERT INTO stat_definitions (",
      "  stat_definition_id, scope, stat_key, display_name, stat_group_id, description, source_priority,",
      "  value_type, aggregation_type, supports_totals, supports_averages, supports_streaks,",
      "  first_recorded_season, first_consistent_season, availability_notes, missing_value_strategy,",
      "  include_pre_consistent_values, is_derived, derivation_sql, is_enabled, sort_order",
      ") VALUES (",
      `  ${index + 1}, ${sqlString(stat.scope)}, ${sqlString(stat.statKey)}, ${sqlString(stat.displayName)}, ${
        groupIdByCode.get(stat.groupCode) ?? "NULL"
      }, ${sqlString(stat.description)}, ${sqlString(stat.sourcePriority)},`,
      `  ${sqlString(stat.valueType)}, ${sqlString(stat.aggregationType)}, ${sqlBoolean(
        stat.supportsTotals
      )}, ${sqlBoolean(stat.supportsAverages)}, ${sqlBoolean(stat.supportsStreaks)},`,
      `  ${sqlNumber(stat.firstRecordedSeason)}, ${sqlNumber(stat.firstConsistentSeason)}, ${sqlString(
        stat.availabilityNotes
      )}, ${sqlString(stat.missingValueStrategy)},`,
      `  ${sqlBoolean(stat.includePreConsistentValues)}, ${sqlBoolean(stat.isDerived)}, ${sqlString(
        stat.derivationSql
      )}, 1, ${sqlNumber(stat.sortOrder)}`,
      ");",
    ].join("\n")
  );
});

statements.push("");
statements.push("COMMIT;");

const sqlOutputPath = path.join(SEED_DIR, "0001_reference_seed.sql");
await fs.writeFile(sqlOutputPath, `${statements.join("\n")}\n`, "utf8");

const metadataOutputPath = path.join(SEED_DIR, "reference_seed_metadata.json");
await fs.writeFile(
  metadataOutputPath,
  `${JSON.stringify(
    {
      competitions,
      statGroups: STAT_GROUPS,
      statDefinitions: STAT_DEFINITIONS,
      approvedPlayerOverrides: approvedOverrides,
    },
    null,
    2
  )}\n`,
  "utf8"
);

console.log("Reference seed SQL:", sqlOutputPath);
console.log("Reference seed metadata:", metadataOutputPath);
console.log("Approved player overrides included:", approvedOverrides.length);
