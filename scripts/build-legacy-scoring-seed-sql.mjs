import fs from "node:fs/promises";
import path from "node:path";
import { SEED_DIR } from "./lib/project-paths.mjs";
import { loadLegacyScoringRows } from "./lib/legacy-supplements.mjs";
import { buildSeasonalAliasLookup, resolveSeasonalAlias } from "./lib/player-splits.mjs";
import { sqlNumber, sqlString } from "./lib/sql.mjs";

const bundlePath = path.join(SEED_DIR, "core_import_bundle.json");
const sqlOutputPath = path.join(SEED_DIR, "0003_legacy_scoring_seed.sql");

function deriveHistoricalPoints(row) {
  const year = Number(row.year);
  const tries = Number(row.tries) || 0;
  const goals = Number(row.goals) || 0;
  const fg1 = Number(row.fg1) || 0;
  const fg2 = Number(row.fg2) || 0;

  const tryValue = year >= 1983 ? 4 : 3;
  const legacyFieldGoalValue = year <= 1970 ? 2 : 1;

  return (tries * tryValue) + (goals * 2) + (fg1 * legacyFieldGoalValue) + (fg2 * 2);
}

const bundle = JSON.parse(await fs.readFile(bundlePath, "utf8"));
const legacyRows = await loadLegacyScoringRows();

const playerIdByName = new Map(bundle.players.map((player, index) => [player.displayName, index + 1]));
const aflAliasLookup = buildSeasonalAliasLookup(bundle.playerAliases, ["afltables"]);

const teamIdByName = new Map(bundle.teams.map((team, index) => [team.canonicalName, index + 1]));
const matchIdByAflKey = new Map();
for (const match of bundle.matches) {
  const aflKey = match.sources?.afltables?.matchKey;
  if (aflKey) {
    matchIdByAflKey.set(aflKey, match.matchId);
  }
}

const statements = [];
statements.push("-- Generated by scripts/build-legacy-scoring-seed-sql.mjs");
statements.push("BEGIN TRANSACTION;");
statements.push("DELETE FROM legacy_player_scoring;");

let legacyId = 1;
for (const row of legacyRows) {
  const resolvedAlias = resolveSeasonalAlias(aflAliasLookup, row.player, row.year, { teamName: row.team });
  statements.push(
    `INSERT INTO legacy_player_scoring (legacy_player_scoring_id, match_id, season, player_id, player_name_raw, team_id, tries, goals, fg1, fg2, points) VALUES (${legacyId}, ${sqlNumber(
      matchIdByAflKey.get(row.match_key) ?? null
    )}, ${sqlNumber(row.year)}, ${sqlNumber(playerIdByName.get(resolvedAlias?.canonicalName ?? "") ?? null)}, ${sqlString(
      row.player
    )}, ${sqlNumber(teamIdByName.get(row.team) ?? null)}, ${sqlNumber(row.tries)}, ${sqlNumber(row.goals)}, ${sqlNumber(
      row.fg1
    )}, ${sqlNumber(row.fg2)}, ${sqlNumber(deriveHistoricalPoints(row))});`
  );
  legacyId += 1;
}

statements.push("COMMIT;");

await fs.writeFile(sqlOutputPath, `${statements.join("\n")}\n`, "utf8");

console.log("Legacy scoring seed SQL:", sqlOutputPath);
console.log("Rows:", legacyRows.length);
