function addStatDefinitions(definitions) {
  for (const definition of definitions) {
    if (!STAT_DEFINITIONS.some((existing) => existing.scope === definition.scope && existing.statKey === definition.statKey)) {
      STAT_DEFINITIONS.push(definition);
    }
  }
}

